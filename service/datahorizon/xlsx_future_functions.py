_WORKSHEET = ("FILTER", "SORT")

PREFIX = {name: "_xlfn." + name for name in _PLAIN}
PREFIX.update({name: "_xlfn._xlws." + name for name in _WORKSHEET})
FUTURE = frozenset(PREFIX)

# Skips string literals and quoted sheet names so a prefix inside them is left alone.
_FILE_PREFIX = re.compile(r'"(?:[^"]|"")*"|\'(?:[^\']|\'\')*\'|_xlfn\.(?:_xlws\.)?', re.IGNORECASE)


def strip_prefix(source):
    """Remove every ``_xlfn.`` / ``_xlfn._xlws.`` prefix outside string literals."""
    return _FILE_PREFIX.sub(lambda match: match[0] if match[0][0] in "\"'" else "", source)
